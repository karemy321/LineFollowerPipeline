"""Extract every ```java block from README.md into ReadmeExamples.java.

Each block becomes one method of class ReadmeExamples. The placeholders the
README uses (camera, robot, myOverlay, canvas, status, ...) are declared once as
fields with tiny stub types, so the snippets compile unchanged. A snippet that
declares its own variable (e.g. `int[] result = ...`) simply shadows the field.

Usage:  py -X utf8 extract_readme_examples.py <README.md> <out_dir>
"""
import re
import sys
from pathlib import Path

readme = Path(sys.argv[1]).read_text(encoding="utf-8")
out_dir = Path(sys.argv[2])
out_dir.mkdir(parents=True, exist_ok=True)

blocks = []
for m in re.finditer(r"^```java\n(.*?)^```", readme, re.S | re.M):
    line = readme.count("\n", 0, m.start()) + 1
    blocks.append((line, m.group(1)))

HEADER = """// GENERATED by extract_readme_examples.py from README.md — do not edit.
import com.example.linefollower.LineFollowerPipeline;

@SuppressWarnings({"unused", "UnusedAssignment"})
public class ReadmeExamples {
    // ---- stand-ins for the placeholders the README uses ----
    static final class Yuv { byte[] y, u, v; }
    interface Camera  { byte[] getGrayscaleFrame(); Yuv getYuvFrame(); }
    interface Robot   { void setSteeringAngle(int s); void setSpeed(int t); }
    interface Overlay {
        void drawHRoi(float top, float bot);
        void drawVRoi(float vTop, float steerRef, float trackRef, float halfBot, float halfTop);
        void drawRoadPath(float[] cols, float[] rows, int n);
        void drawCentroid(float x, boolean found);
    }
    interface Canvas   { void drawRect(float l, float t, float r, float b, Object paint); }
    interface TextView { void setText(String s); }
    interface Swatch   { void setColor(int argb); }

    LineFollowerPipeline pipeline = new LineFollowerPipeline();
    LineFollowerPipeline.Config cfg = new LineFollowerPipeline.Config();
    LineFollowerPipeline.FrameData data = new LineFollowerPipeline.FrameData();
    LineFollowerPipeline.FrameCallback cb = d -> { };
    int[] result = new int[2];
    byte[] grayscaleBytes = new byte[320 * 240];
    int width = 320, height = 240;
    float screenWidth = 1080f, screenHeight = 1920f;
    boolean running = false;
    Camera camera; Robot robot; Overlay myOverlay; Canvas canvas; Object paint;
    TextView status, debug; Swatch lineSwatch, floorSwatch;
"""

body = []
for i, (line, code) in enumerate(blocks, 1):
    indented = "".join("        " + l + "\n" if l.strip() else "\n" for l in code.splitlines())
    body.append(f"\n    // README.md line {line}\n    void example{i:02d}() throws Exception {{\n{indented}    }}\n")

src = HEADER + "".join(body) + "}\n"
(out_dir / "ReadmeExamples.java").write_text(src, encoding="utf-8")
print(f"{len(blocks)} java blocks extracted -> {out_dir / 'ReadmeExamples.java'}")
for i, (line, code) in enumerate(blocks, 1):
    first = code.strip().splitlines()[0]
    print(f"  example{i:02d}  README line {line:4d}  {first[:70]}")
